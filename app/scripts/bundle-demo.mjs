// Bundles data/orion/* into a TS module so the demo works on serverless hosts without filesystem access.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "data", "orion");
const files = Object.fromEntries(
  readdirSync(dir).filter((f) => f !== "answer-key.json").sort().map((f) => [f, readFileSync(join(dir, f), "utf8")]),
);
writeFileSync(
  join(root, "src", "lib", "demo-files.generated.ts"),
  "// AUTO-GENERATED by scripts/bundle-demo.mjs from data/orion. Do not edit.\nexport const DEMO_FILES: Record<string, string> = " + JSON.stringify(files, null, 1) + ";\n",
);
console.log(`bundled ${Object.keys(files).length} demo files`);
